#!/usr/bin/env python3
"""Generate lean/M0Crypto/Release/Ed25519EdwardsCert.lean: ideal-membership certificates
for the twisted Edwards group law.

For the curve a*x^2 + y^2 = 1 + d*x^2*y^2 and the addition of RFC 8032 section 5.1.4,
closure and associativity reduce, once the denominators are cleared, to polynomial
equalities that hold on the curve. Each one is a combination of the curve polynomials
e_i = a*x_i^2 + y_i^2 - 1 - d*x_i^2*y_i^2 with polynomial cofactors. This script finds the
cofactors by multivariate division (sympy `reduced`; {e1, e2, e3} is a Groebner basis over
Q(a, d) because the leading monomials x_i^2*y_i^2 are coprime), checks that they are
polynomials with integer coefficients and that the identity expands to zero, and writes
each identity as a Lean theorem over any commutative ring, proved by `grind`'s ring
normaliser. The script is untrusted: Lean checks every identity.

Usage: uv run --no-project --with sympy==1.14.0 python tools/ed25519_edwards_cert.py
"""
import re
from pathlib import Path

import sympy as sp

OUT = Path(__file__).resolve().parent.parent / "lean/M0Crypto/Release/Ed25519EdwardsCert.lean"

a, d, x1, y1, x2, y2, x3, y3 = sp.symbols("a d x1 y1 x2 y2 x3 y3")
GENS = (x1, y1, x2, y2, x3, y3)


def sum_parts(u1, v1, u2, v2):
    """Numerators and denominators of the sum, as (sympy, Lean) pairs: n/p, m/q."""
    s = {"u1": u1, "v1": v1, "u2": u2, "v2": v2}
    parts = {
        "n": (u1 * v2 + v1 * u2, "({u1} * {v2} + {v1} * {u2})"),
        "p": (1 + d * u1 * u2 * v1 * v2, "(1 + d * {u1} * {u2} * {v1} * {v2})"),
        "m": (v1 * v2 - a * u1 * u2, "({v1} * {v2} - a * {u1} * {u2})"),
        "q": (1 - d * u1 * u2 * v1 * v2, "(1 - d * {u1} * {u2} * {v1} * {v2})"),
    }
    return {k: (e, t.format(**{n: str(v) for n, v in s.items()})) for k, (e, t) in parts.items()}


L = sum_parts(x1, y1, x2, y2)
R = sum_parts(x2, y2, x3, y3)


def lean_side(template):
    """Substitute the parts into a template of the form `{n1} * {q1} * ...`."""
    env = {f"{k}1": v[1] for k, v in L.items()} | {f"{k}2": v[1] for k, v in R.items()}
    sym = {f"{k}1": v[0] for k, v in L.items()} | {f"{k}2": v[0] for k, v in R.items()}
    sym |= {"a": a, "d": d, "x1": x1, "y1": y1, "x2": x2, "y2": y2, "x3": x3, "y3": y3}
    expr = eval(re.sub(r"\{(\w+)\}", r"\1", template).replace("^", "**"), {}, sym)
    return expr, template.format(**env)


CURVES = [(x1, y1), (x2, y2), (x3, y3)]


def curve_poly(x, y):
    return a * x**2 + y**2 - 1 - d * x**2 * y**2


def lean_poly(e):
    s = str(sp.expand(e))
    # An explicit Nat exponent keeps elaboration of the long sums fast.
    return re.sub(r"\*\*(\d+)", r"^(\1 : Nat)", s)


# (name, number of curve equations, left side, right side, doc)
IDENTITIES = [
    ("closure", 2,
     "a * {n1}^2 * {q1}^2 + {m1}^2 * {p1}^2",
     "{p1}^2 * {q1}^2 + d * {n1}^2 * {m1}^2",
     "The sum of two points on the curve is on the curve, with the denominators cleared."),
    ("assoc_x", 3,
     "({n1} * {q1} * y3 + {m1} * {p1} * x3) * ({p2} * {q2} + d * x1 * y1 * {n2} * {m2})",
     "(x1 * {m2} * {p2} + y1 * {n2} * {q2}) * ({p1} * {q1} + d * {n1} * {m1} * x3 * y3)",
     "The x-coordinates of `(P1 + P2) + P3` and `P1 + (P2 + P3)` agree, cross-multiplied."),
    ("assoc_y", 3,
     "({m1} * {p1} * y3 - a * {n1} * {q1} * x3) * ({p2} * {q2} - d * x1 * y1 * {n2} * {m2})",
     "(y1 * {m2} * {p2} - a * x1 * {n2} * {q2}) * ({p1} * {q1} - d * {n1} * {m1} * x3 * y3)",
     "The y-coordinates of `(P1 + P2) + P3` and `P1 + (P2 + P3)` agree, cross-multiplied."),
]

HEADER = '''/-!
Ideal-membership certificates for the twisted Edwards group law.

Generated by `tools/ed25519_edwards_cert.py`. Do not edit by hand.

For the curve `a x² + y² = 1 + d x² y²` and the addition of RFC 8032 section 5.1.4, write
`P1 + P2 = (n/p, m/q)` with `n = x1 y2 + y1 x2`, `p = 1 + d x1 x2 y1 y2`,
`m = y1 y2 - a x1 x2`, `q = 1 - d x1 x2 y1 y2`. Closure and associativity, with the
denominators cleared, are the three equalities below. Each `*_identity` states
`lhs - rhs = c1 e1 + c2 e2 (+ c3 e3)` over any commutative ring, where
`e_i = a x_i² + y_i² - 1 - d x_i² y_i²`; the cofactors `c_i` were computed offline by
multivariate division and are checked here by `grind`'s ring normaliser. The matching
theorem without the suffix substitutes `e_i = 0` for points on the curve.
Cofactor sizes (terms): {sizes}.
-/

namespace M0Crypto.Release.Ed25519EdwardsCert

open Lean.Grind

variable {{R : Type u}} [CommRing R]
'''


def main():
    body = []
    sizes = []
    for name, k, lhs_t, rhs_t, doc in IDENTITIES:
        lhs, lhs_s = lean_side(lhs_t)
        rhs, rhs_s = lean_side(rhs_t)
        es = [curve_poly(*c) for c in CURVES[:k]]
        diff = sp.expand(lhs - rhs)
        quots, rem = sp.reduced(diff, es, *GENS, order="grevlex",
                                domain=sp.QQ.frac_field(a, d))
        assert rem == 0, name
        cofs = []
        for q in quots:
            num, den = sp.fraction(sp.together(q))
            assert den == 1, (name, den)
            cof = sp.Poly(num, *GENS, a, d)
            assert all(c == int(c) for c in cof.coeffs()), name
            cofs.append(sp.expand(num))
        assert sp.expand(diff - sum(c * e for c, e in zip(cofs, es))) == 0, name
        sizes.append(f"{name} " + "/".join(str(len(sp.Poly(c, *GENS, a, d).terms()))
                                           for c in cofs))
        vars_ = "a d x1 y1 x2 y2" + (" x3 y3" if k == 3 else "")
        es_s = [f"(a * {x}^2 + {y}^2 - 1 - d * {x}^2 * {y}^2)" for x, y in CURVES[:k]]
        rhs_cert = "\n      + ".join(f"({lean_poly(c)})\n        * {e}" for c, e in zip(cofs, es_s))
        hyps = "\n    ".join(f"(h{i + 1} : a * {x}^2 + {y}^2 = 1 + d * {x}^2 * {y}^2)"
                             for i, (x, y) in enumerate(CURVES[:k]))
        evars = " ".join(f"e{i + 1}" for i in range(k))
        haves = "\n  ".join(
            f"have e{i + 1} : a * {x}^2 + {y}^2 - 1 - d * {x}^2 * {y}^2 = 0 := by grind"
            for i, (x, y) in enumerate(CURVES[:k]))
        body.append(f"""
/-- {doc} Certificate form. -/
theorem {name}_identity ({vars_} : R) :
    {lhs_s}
      - ({rhs_s})
    = {rhs_cert} := by
  grind

/-- {doc} -/
theorem {name} {{{vars_} : R}}
    {hyps} :
    {lhs_s}
      = {rhs_s} := by
  {haves}
  have key := {name}_identity {vars_}
  rw [{', '.join(evars.split())}] at key
  grind
""")
    text = HEADER.format(sizes=", ".join(sizes)) + "".join(body) + \
        "\nend M0Crypto.Release.Ed25519EdwardsCert\n"
    OUT.write_text(text)


if __name__ == "__main__":
    main()
