#!/usr/bin/env python3
"""Compare the Lean machine model with QEMU on sampled windows of one m0c_x25519 call
(plan docs/design/x25519-proofs.md, phase 11 F).

    python3 -I tools/qemu_x25519_windows.py [--obj OBJ] [--work DIR] [--qemu QEMU]
                                            [--hit N] [--no-model]

A full call is about three million instructions, too many to single-step through the gdb stub.
This script samples it instead. It builds a small test image (tests/startup.S, a generated
driver that calls m0c_x25519 once on RFC 7748 vector 1, and the release object itself), runs it
under QEMU's Cortex-M0 "microbit" machine and single-steps these windows of the one call:

  prologue      entry -> first arrival at the ladder head (clamping, decoding, initial state)
  ladder step   the ladder's `blt` (not taken) at its N-th arrival (--hit, default 7) -> the
                next arrival at the ladder's `cmp`: back edge, one whole ladder step (cswap,
                inline add/sub, ten field-routine calls), counter update
  ladder exit   the ladder head with counter = the `cmp` bound -> the `blt` target (taken)
  doubling exit the doubling loop head with counter 1 -> the `beq` target (taken)
  squaring exit the first squaring loop's head with counter 1 -> the instruction after its
                `bne` (not taken)
  epilogue      the return site of the last field-routine call -> the caller's return address
                (canonical reduction, 32 byte stores, wipe, register restore, `pop {pc}`)

For each window it records QEMU's registers, flags and RAM at the window's first instruction and
the state after every instruction, then runs the model (lean/StepTrace.lean, the same runner as
tools/qemu_steps.py) from the recorded entry state until the first arrival at the window's stop
address. After every instruction r0-r15 and N, Z, C, V must be equal, and at the stop the 16 KiB
of RAM must be equal. Finally the output buffer must equal the RFC 7748 vector.

The windows are found by pattern in the disassembly of the linked image (`llvm-objdump`, symbol
range from `llvm-nm -S`), not by fixed address, and loop iterations are chosen by the counter
slot the code itself names (`str r0, [sp, #...]` after `movs r0, #0xfe`). It checks the model,
not timing, and only the instructions the windows reach; the summary says how many distinct
instructions of the X25519 unit (m0c_fe_mul .. end of m0c_x25519) that is.

--no-model records the QEMU windows and stops (no Lean). The Lean run needs the proofs tree's
M0Crypto.Thumb.FastRun to be built; it does not build anything itself.
"""
import argparse
import importlib.util
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = Path(os.environ.get("M0C_LIB", ROOT.parent)).resolve()
LLVM = Path(os.environ.get("LLVM_BIN", "/opt/homebrew/opt/llvm/bin"))
LLD = Path(os.environ.get("LLD_BIN", "/opt/homebrew/opt/lld/bin"))
RAM = (0x20000000, 0x4000)   # QEMU "microbit": 16 KiB of RAM

# Reuse the gdb client of tools/qemu_steps.py (loaded by path: `python3 -I` does not put the
# script's directory on sys.path).
_spec = importlib.util.spec_from_file_location("qemu_steps", ROOT / "tools" / "qemu_steps.py")
qemu_steps = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(qemu_steps)
Gdb = qemu_steps.Gdb

# RFC 7748 section 5.2, first test vector.
K = "a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4"
U = "e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c"
WANT = "c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552"

DRIVER = r"""
/* Generated by tools/qemu_x25519_windows.py: one m0c_x25519 call on RFC 7748 vector 1. */
typedef unsigned char u8;
int m0c_x25519(u8 out[32], const u8 scalar[32], const u8 point[32]);
static const u8 k[32] = { %s };
static const u8 u[32] = { %s };
static const u8 want[32] = { %s };
u8 x25519_out[32];
int main(void) {
    int bad = 0, i;
    m0c_x25519(x25519_out, k, u);
    for (i = 0; i < 32; i++) bad |= x25519_out[i] ^ want[i];
    return bad != 0;
}
"""


def fail(msg):
    sys.exit(f"qemu_x25519_windows: {msg}")


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        fail(f"{' '.join(map(str, cmd[:3]))} ... failed:\n{(r.stdout + r.stderr).strip()[-600:]}")
    return r.stdout


def cbytes(h):
    return ", ".join(f"0x{h[i:i + 2]}" for i in range(0, len(h), 2))


def text_of(obj):
    """The .text bytes of the release object (what build/lib/text.bin holds)."""
    with tempfile.NamedTemporaryFile(suffix=".bin") as f:
        run([LLVM / "llvm-objcopy", "-O", "binary", "-j", ".text", obj, f.name])
        return Path(f.name).read_bytes()


def build_image(obj, work):
    work.mkdir(parents=True, exist_ok=True)
    drv = work / "x25519_driver.c"
    drv.write_text(DRIVER % (cbytes(K), cbytes(U), cbytes(WANT)))
    flags = ["--target=thumbv6m-none-eabi", "-mcpu=cortex-m0plus", "-mthumb", "-Os",
             "-ffreestanding", "-fno-builtin", "-fno-unwind-tables",
             "-fno-asynchronous-unwind-tables", "-nostdlib", "-Wall", "-Werror"]
    for src in (LIB / "tests" / "startup.S", drv):
        run([LLVM / "clang"] + flags + ["-c", src, "-o", work / (src.name + ".o")])
    elf = work / "x25519_windows.elf"
    run([LLD / "ld.lld", "-T", LIB / "tests" / "microbit.ld", "--build-id=none", "-o", elf,
         work / "startup.S.o", obj, work / "x25519_driver.c.o"])
    return elf


def sized_symbols(elf):
    out = run([LLVM / "llvm-nm", "-S", "--defined-only", elf])
    syms = {}
    for line in out.splitlines():
        f = line.split()
        if len(f) == 4:
            syms[f[3]] = (int(f[0], 16) & ~1, int(f[1], 16))
        elif len(f) == 3:
            syms.setdefault(f[2], (int(f[0], 16) & ~1, 0))
    return syms


LINE = re.compile(r"^\s*([0-9a-f]+):\s+((?:[0-9a-f]{4,8} )+)\s*\t(\S+)(?:\t(.*))?$")


def disasm(elf, start, size):
    out = run([LLVM / "llvm-objdump", "-d", "--triple=thumbv6m-none-eabi",
               f"--start-address={start:#x}", f"--stop-address={start + size:#x}", elf])
    ins = []
    for line in out.splitlines():
        m = LINE.match(line)
        if m and not m.group(3).startswith("."):
            ops = (m.group(4) or "").split("@")[0]
            ins.append((int(m.group(1), 16), " ".join((m.group(3) + " " + ops).split())))
    return ins


def target(text):
    """Absolute target of a branch as llvm-objdump prints it (`bne 0x1234 <sym+0x10>`)."""
    m = re.search(r"\b0x([0-9a-f]+)\b", text.split(None, 1)[1])
    return int(m.group(1), 16)


def find_windows(elf, syms, hit):
    """[(name, start, pick, stop)]: pick is ("hit", n) or ("counter", value)."""
    entry, size = syms["m0c_x25519"]
    ins = disasm(elf, entry, size)
    texts = [t for _, t in ins]

    def only(pred, what):
        idx = [i for i, t in enumerate(texts) if pred(t)]
        if len(idx) != 1:
            fail(f"expected one {what} in m0c_x25519, found {len(idx)}")
        return idx[0]

    i_init = only(lambda t: t == "movs r0, #0xfe", "ladder counter initialisation")
    m = re.fullmatch(r"str r0, \[sp, #(0x[0-9a-f]+)\]", texts[i_init + 1])
    if not m:
        fail("the ladder counter is not stored right after its initialisation")
    slot = int(m.group(1), 16)
    ladder = ins[i_init + 2][0]
    i_blt = only(lambda t: t.startswith("blt "), "blt")
    i_cmp = i_blt - 1
    cm = re.fullmatch(r"cmp r0, #(0x[0-9a-f]+)", texts[i_cmp])
    if not cm or not texts[i_blt + 1].startswith("b ") or target(texts[i_blt + 1]) != ladder:
        fail("the ladder does not end in `cmp r0, #N; blt END; b HEAD`")
    i_beq = only(lambda t: t.startswith("beq "), "beq")
    if not texts[i_beq + 1].startswith("b "):
        fail("the doubling loop does not end in `beq END; b HEAD`")
    dbl = target(texts[i_beq + 1])
    bnes = [i for i, t in enumerate(texts) if t.startswith("bne ")]
    if not bnes:
        fail("no squaring loop (bne) found")
    sq = bnes[0]
    bls = [i for i, t in enumerate(texts) if t.startswith("bl ")]
    last_bl = bls[-1]
    windows = [
        ("prologue", entry, ("hit", 1), ladder),
        ("ladder step", ins[i_blt][0], ("hit", hit), ins[i_cmp][0]),
        ("ladder exit", ladder, ("counter", int(cm.group(1), 16)), target(texts[i_blt])),
        ("doubling exit", dbl, ("counter", 1), target(texts[i_beq])),
        ("squaring exit", target(texts[sq]), ("counter", 1), ins[sq + 1][0]),
        ("epilogue", ins[last_bl][0] + 4, ("hit", 1), None),   # stop: the caller's return address
    ]
    for name, start, _, stop in windows:
        if start == stop:
            fail(f"window {name}: start equals stop")
    return windows, slot


class Session:
    def __init__(self, gdb, slot):
        self.gdb, self.slot = gdb, slot

    def words(self):
        state = self.gdb.regs()
        return state, state.split()

    def counter(self, words):
        sp = int(words[13], 16)
        return int.from_bytes(self.gdb.read(sp + self.slot, 4), "little")

    def run_to(self, addr, pick):
        """Continue to the arrival at `addr` that `pick` selects; return the state there."""
        seen = 0
        while True:
            state, words = self.words()
            if int(words[15], 16) != addr:
                if not self.gdb.run_to([addr]):
                    fail(f"the program ended before {addr:#x}")
                state, words = self.words()
            seen += 1
            kind, val = pick
            if (kind == "hit" and seen == val) or (kind == "counter" and self.counter(words) == val):
                return state, words
            self.gdb.cmd("s")   # leave the address before the breakpoint is set again

    def trace(self, stop):
        """Single-step until the first arrival at `stop` (after at least one step)."""
        steps, pcs = [], set()
        state, words = self.words()
        while True:
            pcs.add(int(words[15], 16))
            self.gdb.cmd("s")
            state, words = self.words()
            steps.append(state)
            if int(words[15], 16) == stop:
                return steps, pcs
            if len(steps) > 200000:
                fail(f"no arrival at {stop:#x} within 200000 steps")


def record(qemu, elf, text, windows, slot, syms):
    tmp = tempfile.mkdtemp()
    path = os.path.join(tmp, "gdb")
    proc = subprocess.Popen(
        [qemu, "-machine", "microbit", "-nographic", "-monitor", "none", "-serial", "none",
         "-semihosting-config", "enable=on,target=native", "-kernel", str(elf), "-S",
         "-chardev", f"socket,id=g,path={path},server=on,wait=on", "-gdb", "chardev:g"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        while not os.path.exists(path):
            if proc.poll() is not None:
                fail("QEMU did not start")
        gdb = Gdb(path)
        flash = gdb.read(0, syms["_etext"][0])
        base = flash.find(text)
        if base < 0:
            fail(f"{elf} does not contain the release object's .text")
        cases = [f"flash 0 {flash.hex()}"]
        s = Session(gdb, slot)
        traced, pcs, ret = {}, set(), None
        for name, start, pick, stop in windows:
            state, words = s.run_to(start, pick)
            if name == "prologue":
                ret = int(words[14], 16) & ~1
            stop = ret if stop is None else stop
            label = name.replace(" ", "_")
            cases += [f"case {label}", f"ram {RAM[0]:x} {gdb.read(*RAM).hex()}",
                      f"regs {state}", f"stop {stop:x}"]
            steps, wpcs = s.trace(stop)
            traced[label] = (steps, gdb.read(*RAM).hex())
            pcs |= wpcs
            print(f"  {name:14} {start:#07x} -> {stop:#07x}: {len(steps)} instructions", flush=True)
        out = gdb.read(syms["x25519_out"][0], 32).hex()
        if out != WANT:
            fail(f"QEMU output {out} differs from the RFC 7748 vector")
        lo = syms["m0c_fe_mul"][0]
        hi = syms["m0c_x25519"][0] + syms["m0c_x25519"][1]
        unit = {a for a, _ in disasm(elf, lo, hi - lo)}
        return cases, traced, len(pcs & unit), len(unit)
    finally:
        proc.kill()
        proc.wait()
        if os.path.exists(path):
            os.unlink(path)
        os.rmdir(tmp)


def compare(cases, traced, work, timeout):
    case_file = work / "x25519_windows_cases.txt"
    case_file.write_text("\n".join(cases) + "\n")
    env = dict(os.environ, PATH=os.path.expanduser("~/.elan/bin") + ":" + os.environ["PATH"])
    r = subprocess.run(["nice", "-n", "5", "perl", "-e", f"alarm {timeout}; exec @ARGV",
                        "lake", "env", "lean", "--run", "lean/StepTrace.lean", str(case_file)],
                       cwd=ROOT, env=env, capture_output=True, text=True)
    if r.returncode:
        fail(f"the model run failed (status {r.returncode}): {(r.stdout + r.stderr).strip()[-400:]}")
    model, name = {}, None
    for line in r.stdout.splitlines():
        if line.startswith("case "):
            name = line[5:]
            model[name] = []
        elif name is not None:
            model[name].append(line)
    total = 0
    for name, (steps, ram) in traced.items():
        got = model.get(name, [])
        for i, (want, have) in enumerate(zip(steps + ["ram " + ram], got)):
            if want != have:
                before = steps[i - 1] if i else "(entry)"
                fail(f"{name}: the model and QEMU differ after instruction {i + 1}\n"
                     f"  state before: {before}\n  QEMU:  {want[:160]}\n  model: {have[:160]}")
        if len(got) != len(steps) + 1:
            fail(f"{name}: QEMU ran {len(steps)} instructions, the model printed {len(got)} lines; "
                 f"last: {got[-1][:160] if got else ''}")
        total += len(steps)
    return total


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--obj", default=str(LIB / "build" / "lib" / "m0crypto.o"))
    ap.add_argument("--work", default="/tmp/m0c-x25519-windows")
    ap.add_argument("--qemu", default=os.environ.get("QEMU", "qemu-system-arm"))
    ap.add_argument("--hit", type=int, default=7, help="which ladder step to trace (1-based)")
    ap.add_argument("--no-model", action="store_true", help="record QEMU windows only")
    ap.add_argument("--timeout", type=int, default=900, help="seconds for the Lean model run")
    args = ap.parse_args()
    if args.hit < 1:
        fail("--hit must be at least 1")
    obj, work = Path(args.obj).resolve(), Path(args.work).resolve()
    text = text_of(obj)
    elf = build_image(obj, work)
    syms = sized_symbols(elf)
    windows, slot = find_windows(elf, syms, args.hit)
    print(f"image {elf}; counter slot sp+{slot:#x}")
    cases, traced, covered, unit = record(args.qemu, elf, text, windows, slot, syms)
    steps = sum(len(s) for s, _ in traced.values())
    print(f"QEMU: {steps} instructions in {len(traced)} windows, {covered} of the unit's {unit} "
          f"instructions; output equals RFC 7748 vector 1")
    if args.no_model:
        print("model comparison skipped (--no-model)")
        return
    total = compare(cases, traced, work, args.timeout)
    print(f"ok: model and QEMU agree after each of {total} instructions in {len(traced)} windows "
          f"of one m0c_x25519 call ({covered} of {unit} distinct instructions of the X25519 unit), "
          f"and on the RAM at each window's end")


if __name__ == "__main__":
    main()
