#!/usr/bin/env python3
"""Extract a linked Thumb symbol's exact bytes from an ELF into a Lean artifact file.

The generated Lean file is checked in so proofs build without the ARM toolchain.
`--check` regenerates in memory and fails if the checked-in file differs, which
ties the proofs to the bytes produced by tools/build.sh.

Standard library only. Supports little-endian ELF32 ARM executables only.

Usage:
  extract_artifact.py ELF SYMBOL LEAN_MODULE OUT.lean [--check]
"""
import hashlib
import struct
import sys


def fail(msg):
    sys.exit(f"extract_artifact: {msg}")


def need(data, off, length, what):
    if off < 0 or length < 0 or off + length > len(data):
        fail(f"{what} [{off}, {off + length}) lies outside the {len(data)}-byte file")


def parse_elf(data):
    need(data, 0, 52, "ELF header")
    if data[:4] != b"\x7fELF":
        fail("not an ELF file")
    if data[4] != 1 or data[5] != 1:
        fail("expected ELFCLASS32, little-endian")
    (e_type, e_machine, _ver, _entry, _phoff, e_shoff, _flags, _ehsize,
     _phentsize, _phnum, e_shentsize, e_shnum, e_shstrndx) = struct.unpack_from(
        "<HHIIIIIHHHHHH", data, 16)
    if e_type != 2:
        fail("expected ET_EXEC (linked executable)")
    if e_machine != 40:
        fail("expected EM_ARM")
    if e_shentsize != 40:
        fail("unexpected section header size")
    need(data, e_shoff, e_shnum * e_shentsize, "section header table")
    if e_shstrndx >= e_shnum:
        fail("invalid section name string table index")
    sections = []
    for i in range(e_shnum):
        sh = struct.unpack_from("<IIIIIIIIII", data, e_shoff + i * e_shentsize)
        sections.append(dict(name=sh[0], type=sh[1], flags=sh[2], addr=sh[3],
                             offset=sh[4], size=sh[5], link=sh[6], entsize=sh[9]))
    shstr = sections[e_shstrndx]

    for s in sections:
        if s["type"] != 8:  # SHT_NOBITS occupies no file bytes
            need(data, s["offset"], s["size"], "section")

    def cstr(table, off):
        if off >= table["size"]:
            fail("string offset outside its table")
        start = table["offset"] + off
        end = data.find(b"\0", start, table["offset"] + table["size"])
        if end < 0:
            fail("unterminated string")
        return data[start:end].decode()

    for s in sections:
        s["name_str"] = cstr(shstr, s["name"])
    return sections, cstr


def find_symbol(data, sections, cstr, name):
    symtabs = [s for s in sections if s["type"] == 2]  # SHT_SYMTAB
    if len(symtabs) != 1:
        fail("expected exactly one SHT_SYMTAB")
    symtab = symtabs[0]
    if symtab["link"] >= len(sections) or symtab["size"] % 16:
        fail("malformed SHT_SYMTAB")
    strtab = sections[symtab["link"]]
    found = []
    for off in range(0, symtab["size"], 16):
        st_name, st_value, st_size, st_info, _other, st_shndx = struct.unpack_from(
            "<IIIBBH", data, symtab["offset"] + off)
        if cstr(strtab, st_name) == name:
            found.append((st_value, st_size, st_info, st_shndx))
    if len(found) != 1:
        fail(f"expected exactly one symbol {name!r}, found {len(found)}")
    value, size, info, shndx = found[0]
    if shndx == 0 or shndx >= len(sections):
        fail(f"{name} is not defined in a regular section")
    if info & 0xF != 2:
        fail(f"{name} is not STT_FUNC")
    if value & 1 != 1:
        fail(f"{name} lacks the Thumb bit")
    if size == 0 or size % 2:
        fail(f"{name} has invalid size {size}")
    return value & ~1, size, sections[shndx]


def extract(elf_path, symbol):
    data = open(elf_path, "rb").read()
    sections, cstr = parse_elf(data)
    addr, size, sec = find_symbol(data, sections, cstr, symbol)
    if sec["type"] != 1 or not sec["flags"] & 0x4:  # SHT_PROGBITS, SHF_EXECINSTR
        fail(f"{symbol} is not in an executable PROGBITS section")
    if not (sec["addr"] <= addr and addr + size <= sec["addr"] + sec["size"]):
        fail(f"{symbol} extends outside section {sec['name_str']}")
    start = sec["offset"] + addr - sec["addr"]
    need(data, start, size, f"{symbol} bytes")
    code = data[start:start + size]
    if len(code) != size:
        fail(f"{symbol}: extracted {len(code)} bytes, expected {size}")
    return addr, code, hashlib.sha256(data).hexdigest(), sec["name_str"]


def render(module, symbol, addr, code, elf_sha, section):
    code_sha = hashlib.sha256(code).hexdigest()
    rows = []
    for i in range(0, len(code), 8):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in code[i:i + 8]))
    body = ",\n".join(rows)
    return f"""-- GENERATED by tools/extract_artifact.py. Do not edit; run tools/check.sh.
-- Source ELF sha256: {elf_sha}
-- Symbol: {symbol} in section {section}
-- Fragment sha256: {code_sha}

namespace {module}

/-- Link address of the first byte of `{symbol}` (Thumb bit cleared). -/
def base : Nat := 0x{addr:08x}

/-- Exact linked bytes of `{symbol}` ({len(code)} bytes). -/
def bytes : List (BitVec 8) := [
{body}
  ]

/-- SHA-256 of the source ELF, recorded for provenance. -/
def elfSha256 : String := "{elf_sha}"

/-- SHA-256 of `bytes`, recorded for provenance. -/
def fragmentSha256 : String := "{code_sha}"

end {module}
"""


def main(argv):
    if len(argv) not in (5, 6) or (len(argv) == 6 and argv[5] != "--check"):
        fail(__doc__)
    elf, symbol, module, out = argv[1:5]
    addr, code, elf_sha, section = extract(elf, symbol)
    text = render(module, symbol, addr, code, elf_sha, section)
    if len(argv) == 6:
        try:
            current = open(out).read()
        except FileNotFoundError:
            fail(f"{out} missing")
        if current != text:
            fail(f"{out} is stale relative to {elf}; rerun without --check")
        print(f"ok: {out} matches {elf} ({len(code)} bytes, elf sha256 {elf_sha})")
    else:
        open(out, "w").write(text)
        print(f"wrote {out} ({len(code)} bytes)")


if __name__ == "__main__":
    main(sys.argv)
