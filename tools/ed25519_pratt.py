#!/usr/bin/env python3
"""Generate lean/M0Crypto/Release/Ed25519PrimeCert.lean: a Pratt certificate for
p = 2^255 - 19.

Factors p - 1 recursively with sympy, picks the smallest Lucas witness for each prime of
the tree, and writes the steps in increasing order, so each step's factors are 2 or an
earlier step. The script is untrusted: Lean checks the certificate by kernel evaluation
(`Ed25519Prime.check`).

Usage: uv run --no-project --with sympy==1.14.0 python tools/ed25519_pratt.py
"""
from pathlib import Path

import sympy as sp

OUT = Path(__file__).resolve().parent.parent / "lean/M0Crypto/Release/Ed25519PrimeCert.lean"
P = 2**255 - 19


def lucas_step(n):
    """The smallest witness of n and the prime factors of n - 1 with multiplicity."""
    fs = sp.factorint(n - 1)
    for a in range(2, n):
        if pow(a, n - 1, n) == 1 and all(pow(a, (n - 1) // q, n) != 1 for q in fs):
            return a, sorted(q for q, e in fs.items() for _ in range(e))
    raise ValueError(n)


def tree(n, steps):
    if n == 2 or n in steps:
        return
    a, fs = lucas_step(n)
    steps[n] = (a, fs)
    for q in set(fs):
        tree(q, steps)


def main():
    steps = {}
    tree(P, steps)
    a_p, fs_p = steps.pop(P)
    rows = ",\n".join(f"  ⟨{n}, {a}, [{', '.join(map(str, fs))}]⟩"
                      for n, (a, fs) in sorted(steps.items()))
    OUT.write_text(f'''import M0Crypto.Release.Ed25519Prime

/-!
Primality of `p = 2^255 - 19` and Fermat's little theorem at `p`.

Generated by `tools/ed25519_pratt.py`. Do not edit by hand.

`steps` is a Pratt certificate: a Lucas step for each of the {len(steps)} odd primes below `p`
in the factor tree of `p - 1`, smallest first, then `stepP` for `p`. The kernel evaluates
`check` on it with `Nat.powMod` (`decide +kernel`).
-/

namespace M0Crypto.Release.Ed25519PrimeCert

open M0Crypto.Release.Ed25519Prime

/-- The field prime of RFC 8032, `2^255 - 19`. -/
def p : Nat := 2 ^ 255 - 19

/-- Lucas steps for the odd primes of the factor tree of `p - 1`, smallest first. -/
def steps : List Step := [
{rows}
]

/-- The Lucas step for `p`. -/
def stepP : Step := ⟨p, {a_p}, [{', '.join(map(str, fs_p))}]⟩

theorem check_steps : check [2] (steps ++ [stepP]) = true := by decide +kernel

theorem prime_fermat_p : Prime p ∧ Fermat p :=
  check_sound (fun _ hr => List.mem_singleton.mp hr ▸ prime_two) check_steps stepP
    (List.mem_append.mpr (Or.inr (List.mem_singleton.mpr rfl)))

theorem prime_p : Prime p := prime_fermat_p.1

/-- Fermat's little theorem at `p`. -/
theorem fermat_p : Fermat p := prime_fermat_p.2

end M0Crypto.Release.Ed25519PrimeCert
''')


if __name__ == "__main__":
    main()
